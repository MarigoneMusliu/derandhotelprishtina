"""One-off: switch every internal page link to clean capitalised URLs (/Rooms, /Home)
and regenerate the clean-URL block in .htaccess. Run from the site root."""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

STEMS = sorted(os.path.splitext(f)[0] for f in glob.glob("*.html"))


RENAMED = {"index": "Home", "extra": "Concierge", "perfumes": "Parfumes", "explorederand": "ExploreDerand", "orion": "ConferenceHall", "ticketsadmin": "TicketsAdmin"}


def clean(stem):
    if stem in RENAMED:
        return RENAMED[stem]
    return "-".join(s[:1].upper() + s[1:] for s in stem.split("-"))


MAP = {s: clean(s) for s in STEMS}
NAMES = "|".join(re.escape(s) for s in sorted(STEMS + ["home"], key=len, reverse=True))
DOMAIN = r"https?://(?:www\.)?derandhotel\.com"


def target(name):
    return "/" + (MAP.get(name) or ("Home" if name == "home" else name))


re_domain = re.compile(DOMAIN + r"/(" + NAMES + r")(?:\.html)?(?=[?#\"'\s<),]|$)")
re_html = re.compile(r"(?<=[\"'(=\s,>])(?:\./|/)?(" + NAMES + r")\.html(?=[?#\"'\s)<,&]|$)")
re_attr = re.compile(
    r"(\b(?:href|action|src|formaction|data-[\w-]*(?:href|url|link))\s*=\s*)([\"'])(?:\./|/)?("
    + NAMES + r")(?=[?#\"'])"
)


def domain_sub(m):
    name = m.group(1)
    if name in ("index", "home"):
        return "https://www.derandhotel.com/"
    return "https://www.derandhotel.com" + target(name)


def convert(text, is_html):
    text = re_domain.sub(domain_sub, text)
    text = re_html.sub(lambda m: target(m.group(1)), text)
    if is_html:
        text = re_attr.sub(lambda m: m.group(1) + m.group(2) + target(m.group(3)), text)
    return text


VENDOR = re.compile(r"(\.min\.js$|^jquery|^bootstrap|^owl|^slicknav|^perfume-shop-d)")
files = glob.glob("*.html") + ["sitemap.xml", "robots.txt"] + glob.glob("api/*.php")
files += [f for f in glob.glob("js/*.js") if not VENDOR.search(os.path.basename(f))]

changed = []
for f in files:
    raw = open(f, "rb").read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw[3:].decode("utf-8") if bom else raw.decode("utf-8")
    new = convert(text, f.endswith(".html"))
    if new != text:
        open(f, "wb").write((b"\xef\xbb\xbf" if bom else b"") + new.encode("utf-8"))
        changed.append(f)

lines = [
    "# BEGIN clean-urls (generated by _tools/clean_urls.py)",
    "<IfModule mod_rewrite.c>",
    "  # Old /page.html, lowercase or trailing-slash requests -> canonical /Page (301);",
    "  # /Page is then served from page.html internally.",
]
for stem in STEMS:
    name = MAP[stem]
    alias = "(%s(\\.html)?|%s)" % (re.escape(stem), re.escape(name))
    lines += [
        "  RewriteCond %%{THE_REQUEST} \\s/+%s/?[\\s?] [NC]" % alias,
        "  RewriteCond %%{THE_REQUEST} !\\s/+%s[\\s?]" % re.escape(name),
        "  RewriteRule ^ /%s [R=301,L]" % name,
        "  RewriteRule ^%s$ %s.html [L]" % (re.escape(name), stem),
    ]
lines += ["</IfModule>", "# END clean-urls"]
block = "\n".join(lines)

ht = open(".htaccess", encoding="utf-8").read()
ht = re.sub(
    r"  # /index\.html -> / \(avoid duplicate home page URLs\)\n  RewriteCond %\{THE_REQUEST\} \\s/index\\\.html\[\\s\?\]\n  RewriteRule \^index\\\.html\$ https://www\.derandhotel\.com/ \[R=301,L\]\n\n",
    "",
    ht,
)
if "# BEGIN clean-urls" in ht:
    ht = re.sub(r"# BEGIN clean-urls.*?# END clean-urls", lambda m: block, ht, flags=re.S)
else:
    marker = "<IfModule mod_mime.c>"
    ht = ht.replace(marker, block + "\n\n" + marker, 1)
open(".htaccess", "w", encoding="utf-8", newline="\n").write(ht)

print("pages:", len(STEMS))
print("files changed:", len(changed))
for f in changed:
    print("  ", f)
